import numpy as np

def residual_and_jacobian(w, param):
    # -------------------------
    # unknowns: w = [D,B,L,V,x1,x2,x3,y1,y2,y3]
    # -------------------------
    D, B, L, V, x1, x2, x3, y1, y2, y3 = w

    # -------------------------
    # params: [F, z, q, r, b, alp]
    # -------------------------
    F, z, q, r, b, alp = param

    # helpers
    def y_eq(x):
        return alp * x / (1.0 + (alp - 1.0) * x)

    def dy_dx(x):
        den = 1.0 + (alp - 1.0) * x
        return alp / (den * den)

    # convenience
    A = (L + q * F)           # (L + qF)
    G = (V + (1.0 - q) * F)   # (V + (1-q)F)

    res = np.zeros(10)
    J   = np.zeros((10, 10))

    # indices: [D,B,L,V,x1,x2,x3,y1,y2,y3]
    iD,iB,iL,iV = 0,1,2,3
    ix1,ix2,ix3 = 4,5,6
    iy1,iy2,iy3 = 7,8,9

    # ------------------------------------------------------------
    # r2 = r*D - L
    # ------------------------------------------------------------
    res[0] = r*D - L
    J[0,iD] = r
    J[0,iL] = -1.0

    # ------------------------------------------------------------
    # r3 = b*B - V
    # ------------------------------------------------------------
    res[1] = b*B - V
    J[1,iB] = b
    J[1,iV] = -1.0

    # ------------------------------------------------------------
    # r4 = D + L - V - (1-q)*F
    # ------------------------------------------------------------
    res[2] = D + L - V - (1.0 - q)*F
    J[2,iD] = 1.0
    J[2,iL] = 1.0
    J[2,iV] = -1.0

    # ------------------------------------------------------------
    # r5 = V + B - L - q*F
    # ------------------------------------------------------------
    res[3] = V + B - L - q*F
    J[3,iV] = 1.0
    J[3,iB] = 1.0
    J[3,iL] = -1.0

    # ------------------------------------------------------------
    # r6 = (L+qF)x2 + Vx1 - (L+qF)x1 - V*y1
    # ------------------------------------------------------------
    res[4] = A*x2 + V*x1 - A*x1 - V*y1

    # d/dL: (x2 - x1) because dA/dL = 1
    J[4,iL]  = (x2 - x1)
    # d/dV: (x1 - y1)
    J[4,iV]  = (x1 - y1)
    # d/dx1: (V - A)
    J[4,ix1] = (V - A)
    # d/dx2: A
    J[4,ix2] = A
    # d/dy1: -V
    J[4,iy1] = -V

    # ------------------------------------------------------------
    # r7 = y1 - y_eq(x1)
    # ------------------------------------------------------------
    res[5] = y1 - y_eq(x1)
    J[5,iy1] = 1.0
    J[5,ix1] = -dy_dx(x1)

    # ------------------------------------------------------------
    # r8 = Lx3 + Fz + V*y1 - (L+qF)x2 - (V+(1-q)F)y2
    # ------------------------------------------------------------
    res[6] = L*x3 + F*z + V*y1 - A*x2 - G*y2

    # d/dL: x3 - x2  (since A depends on L)
    J[6,iL]  = (x3 - x2)
    # d/dV: y1 - y2  (since G depends on V)
    J[6,iV]  = (y1 - y2)
    # d/dx2: -A
    J[6,ix2] = -A
    # d/dx3: L
    J[6,ix3] = L
    # d/dy1: V
    J[6,iy1] = V
    # d/dy2: -G
    J[6,iy2] = -G

    # ------------------------------------------------------------
    # r9 = y2 - y_eq(x2)
    # ------------------------------------------------------------
    res[7] = y2 - y_eq(x2)
    J[7,iy2] = 1.0
    J[7,ix2] = -dy_dx(x2)

    # ------------------------------------------------------------
    # r10 = L*y3 + (V+(1-q)F)*y2 - L*x3 - (V+(1-q)F)*y3
    #     = L*(y3 - x3) + G*(y2 - y3)
    # ------------------------------------------------------------
    res[8] = L*y3 + G*y2 - L*x3 - G*y3

    # d/dL: (y3 - x3)
    J[8,iL]  = (y3 - x3)
    # d/dV: (y2 - y3) because dG/dV = 1
    J[8,iV]  = (y2 - y3)
    # d/dx3: -L
    J[8,ix3] = -L
    # d/dy2: G
    J[8,iy2] = G
    # d/dy3: L - G
    J[8,iy3] = (L - G)


    # ------------------------------------------------------------
    # r11 = y3 - y_eq(x3)
    # ------------------------------------------------------------
    res[9] = y3 - y_eq(x3)
    J[9,iy3] = 1.0
    J[9,ix3] = -dy_dx(x3)

    return res, J

